/**
 * Writes src/lib/forms/helveticaMetrics.ts: Helvetica's glyph widths and
 * kerning pairs (per 1000 em) for every character pdfSafe() lets through,
 * taken from pdf-lib itself so the browser measures text exactly as the
 * PDF filler does.
 *
 *   npx tsx tools/forms-mapping/gen_helvetica_metrics.ts
 */
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { PDFDocument, StandardFonts } from 'pdf-lib'

async function main() {
  const doc = await PDFDocument.create()
  const font = await doc.embedFont(StandardFonts.Helvetica)
  const chars: string[] = []
  for (let c = 0x20; c <= 0x7e; c++) chars.push(String.fromCharCode(c))
  for (let c = 0xa0; c <= 0xff; c++) chars.push(String.fromCharCode(c))
  const w = (s: string) => font.widthOfTextAtSize(s, 1000)
  const widths: Record<string, number> = {}
  for (const ch of chars) widths[ch] = Math.round(w(ch))
  const kern: Record<string, number> = {}
  for (const a of chars) {
    for (const b of chars) {
      const k = Math.round(w(a + b) - widths[a] - widths[b])
      if (k !== 0) kern[a + b] = k
    }
  }
  const out = [
    '// Generated by tools/forms-mapping/gen_helvetica_metrics.ts from pdf-lib. Do not edit.',
    '',
    '/** Helvetica glyph widths, per 1000 em, for every character pdfSafe() keeps. */',
    `export const HELVETICA_WIDTHS: Record<string, number> = ${JSON.stringify(widths)}`,
    '',
    '/** Helvetica kerning between two characters, per 1000 em (pdf-lib counts it when measuring). */',
    `export const HELVETICA_KERNING: Record<string, number> = ${JSON.stringify(kern)}`,
    '',
  ].join('\n')
  writeFileSync(path.join(process.cwd(), 'src', 'lib', 'forms', 'helveticaMetrics.ts'), out)
  console.log('widths', Object.keys(widths).length, 'kerning pairs', Object.keys(kern).length)
}

void main()
